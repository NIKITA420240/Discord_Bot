class GeometryRAG:
    def __init__(self, hf_token: str):
        print("⏳ [AI Service] Инициализация FastEmbed (MiniLM)...")
        self.embedder = TextEmbedding(model_name="sentence-transformers/paraphrase-multilingual-MiniLM-L12-v2", threads=1)
        self.client = AsyncInferenceClient(model="Qwen/Qwen2.5-72B-Instruct", token=hf_token)
        
        self.df = self._create_knowledge_base()
        
        print("⏳ [AI Service] Векторизация базы знаний...")
        passages = self.df['text_for_search'].tolist()
        self.kb_vectors = np.array(list(self.embedder.embed(passages)))
        
        print("✅ [AI Service] Готов к работе (Hybrid Search: Vector + Keyword)!")

    def _create_knowledge_base(self):
        data = []
        lines = KNOWLEDGE_BASE.split('\n')
        current_section = "Общее"
        pattern = re.compile(r'^\d+\)\s+(.*?)\s+[–—]\s+(.*)$')
        
        for line in lines:
            line = line.strip().replace('-', '—')
            if "ПЛАНИМЕТРИЯ" in line: current_section = "ПЛАНИМЕТРИЯ"
            if "СТЕРЕОМЕТРИЯ" in line: current_section = "СТЕРЕОМЕТРИЯ"
            if "МЕТОД КООРДИНАТ" in line: current_section = "МЕТОД КООРДИНАТ"
            
            match = pattern.match(line)
            if match:
                statement = match.group(1).strip()
                source = match.group(2).strip()
                
                # Добавляем чистое название для поиска по ключевым словам
                data.append({
                    "statement": statement,
                    "source": source,
                    "text_for_search": f"{statement} {current_section}", # Для вектора
                    "full_text": f"Теорема: {statement} (Раздел: {current_section}). Источник: {source}"
                })
        
        # Матрицы
        data.append({
            "statement": "Использование определителей и матриц",
            "source": "Рекомендации",
            "text_for_search": "Можно ли использовать определители, матрицы, векторное произведение? Метод координат",
            "full_text": "Метод координат. Использование определителей, матриц. Формально разрешено, но НЕ рекомендуется."
        })
        return pd.DataFrame(data)

    def cosine_similarity_np(self, a, b):
        norm_a = np.linalg.norm(a)
        norm_b = np.linalg.norm(b, axis=1)
        return np.dot(b, a) / (norm_b * norm_a)

    def calculate_keyword_boost(self, query: str, documents: list):
        """
        Простая функция, которая проверяет совпадение слов.
        Если слово из запроса есть в документе -> накидываем очки.
        """
        query_words = set(re.findall(r'\w+', query.lower()))
        scores = []
        
        for doc in documents:
            doc_lower = doc.lower()
            score = 0.0
            for word in query_words:
                if len(word) > 2 and word in doc_lower: # Игнорируем предлоги
                    score += 0.3 # БОНУС за совпадение слова (30% к уверенности)
            scores.append(score)
            
        return np.array(scores)

    async def get_answer(self, query: str):
        loop = asyncio.get_running_loop()
        
        # 1. Векторный поиск (Смысл)
        query_vec = await loop.run_in_executor(None, lambda: list(self.embedder.embed([query]))[0])
        vector_scores = self.cosine_similarity_np(query_vec, self.kb_vectors)
        
        # 2. Поиск по ключевым словам (Точность)
        keyword_scores = self.calculate_keyword_boost(query, self.df['statement'].tolist())
        
        # 3. ГИБРИДНЫЙ СЧЕТ (Сумма)
        final_scores = vector_scores + keyword_scores
        
        # Берем ТОП-3 по финальному счету
        top_k_indices = np.argsort(final_scores)[-3:][::-1]
        
        # Проверяем лидера. Если даже с бонусом он < 0.5, значит ничего нет
        if final_scores[top_k_indices[0]] < 0.5:
             return "❌ В списке разрешенных теорем ничего похожего не найдено."

        # Собираем контекст для LLM
        candidates_text = ""
        for i, idx in enumerate(top_k_indices):
            row = self.df.iloc[idx]
            score_val = final_scores[idx]
            candidates_text += f"Кандидат #{i+1} (Score: {score_val:.2f}): {row['full_text']}\n"

        # 4. Qwen принимает решение
        prompt = f"""
        <|im_start|>system
        Ты — методист ЕГЭ. Найди ответ среди кандидатов.
        
        Вопрос: "{query}"
        
        Кандидаты (отсортированы по релевантности):
        {candidates_text}
        
        ИНСТРУКЦИЯ:
        1. Если кандидат прямо отвечает на вопрос (совпадают названия теорем) -> "✅ Да, можно без доказательства." + источник.
        2. Если вопрос про Матрицы -> Перескажи риски.
        3. Если ни один кандидат не подходит по смыслу -> "❌ Нет, в списке не найдено."
        <|im_end|>
        <|im_start|>assistant
        """
        
        try:
            response = await self.client.chat_completion(
                messages=[{"role": "user", "content": prompt}],
                max_tokens=300,
                temperature=0.0
            )
            return response.choices[0].message.content
        except Exception as e:
            return f"⚠️ Ошибка нейросети: {e}"